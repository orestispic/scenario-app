// Mechanical import from the user-supplied archive, kept verbatim in docs.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const source='docs/design-system/source/Senario_UI_Blocks_Design_System.html';
const html=readFileSync(source,'utf8');
const tokens=html.match(/:root\{[\s\S]*?\n\}/)?.[0];
const symbols=html.match(/<symbol[\s\S]*?<\/symbol>/g);
if(!tokens||symbols?.length!==21)throw new Error('Unexpected design system structure');
mkdirSync('src/ui',{recursive:true});
writeFileSync('src/ui/tokens.css',`/* Verbatim tokens from Senario UI Blocks v3.0. Generated by import-ui-blocks.mjs. */\n${tokens}\n`);
writeFileSync('public/senario-ui-icons.svg',`<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`);
writeFileSync('public/ui-check.svg',`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round">${symbols[0].replace(/<\/?symbol[^>]*>/g,'')}</svg>`);
copyFileSync('docs/design-system/source/senario-logo.png','public/senario-logo.png');
writeFileSync('src/ui/fonts.css',readFileSync('src/designSystem.css','utf8').split(':root {')[0].trimEnd()+'\n');
console.log(`Imported 21 icons and tokens; source SHA256 ${createHash('sha256').update(html).digest('hex')}`);
